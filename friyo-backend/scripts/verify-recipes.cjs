// Uses ONLY the disposable verification database. Never reads .env credentials.
require('reflect-metadata');
const assert = require('node:assert/strict');
const path = require('node:path');
const buildDir = process.env.FRIYO_VERIFY_BUILD_DIR || path.resolve(__dirname, '../dist');
const { DataSource } = require('typeorm');
const { ConfigService } = require('@nestjs/config');
const { Recipe, RecipeDifficulty, RecipeReviewStatus, RecipeStatus } = require(path.join(buildDir, 'database/entities/recipe.entity'));
const { RecipeIngredient } = require(path.join(buildDir, 'database/entities/recipe-ingredient.entity'));
const { RecipeStep } = require(path.join(buildDir, 'database/entities/recipe-step.entity'));
const { RecipeAdaptation } = require(path.join(buildDir, 'database/entities/recipe-adaptation.entity'));
const { UserProfile } = require(path.join(buildDir, 'database/entities/user-profile.entity'));
const { FridgeItem } = require(path.join(buildDir, 'database/entities/fridge-item.entity'));
const { Ingredient, IngredientCategory } = require(path.join(buildDir, 'database/entities/ingredient.entity'));
const { AdminUser } = require(path.join(buildDir, 'database/entities/admin-user.entity'));
const { User } = require(path.join(buildDir, 'database/entities/user.entity'));
const { RecipesService } = require(path.join(buildDir, 'modules/recipes/recipes.service'));
const { RecipeRecommendationService } = require(path.join(buildDir, 'modules/recipes/recipe-recommendation.service'));
const { ExternalRecipesService } = require(path.join(buildDir, 'modules/recipes/external-recipes.service'));

(async () => {
  const db = new DataSource({ type: 'postgres', host: '127.0.0.1', port: 15432, username: 'friyo_test', password: 'friyo_test_local', database: 'friyo_recipe_verification', entities: [path.join(buildDir, '**/*.entity.js')], migrations: [path.join(buildDir, 'database/migrations/*.js')], synchronize: false });
  await db.initialize();
  try {
    await db.runMigrations();
    const repo = entity => db.getRepository(entity);
    const remote = new ExternalRecipesService(new ConfigService({ THEMEALDB_API_KEY: '1' }), db);
    const service = new RecipesService(repo(Recipe), repo(RecipeIngredient), repo(RecipeStep), repo(RecipeAdaptation), repo(UserProfile), repo(FridgeItem), repo(Ingredient), repo(AdminUser), {}, db, remote);
    const recommendations = new RecipeRecommendationService(repo(Recipe), repo(RecipeAdaptation), repo(RecipeIngredient), repo(FridgeItem), repo(UserProfile), repo(Ingredient), {}, new ConfigService({ OPENAI_API_KEY: 'test-unused' }), db);
    const user = await repo(User).save(repo(User).create({ name: 'Recipe verification' }));
    const authored = await service.createRecipe(user.id, { title: '家常汤', title_en: 'Home soup', description: '中文原文', description_en: 'Chinese original', ingredients: [{ display_name: '番茄', display_name_en: 'Tomato', display_name_zh: '番茄' }], steps: [{ step_number: 1, description: '煮汤。', description_en: 'Simmer soup.', tips_zh: '保持小火。' }] });
    const authoredDetail = await repo(Recipe).findOneOrFail({ where: { id: authored.id }, relations: ['ingredients', 'steps'] });
    assert.equal(authoredDetail.titleEn, 'Home soup');
    assert.equal(authoredDetail.ingredients[0].displayNameEn, 'Tomato');
    assert.equal(authoredDetail.steps[0].descriptionEn, 'Simmer soup.');
    assert.equal(authoredDetail.steps[0].tipsZh, '保持小火。');
    await service.updateRecipe(authored.id, user.id, { title_en: 'Updated home soup' });
    assert.equal((await repo(Recipe).findOneByOrFail({ id: authored.id })).titleEn, 'Updated home soup');
    console.log('PASS: bilingual recipe create/update persistence');
    const tomato = await repo(Ingredient).save(repo(Ingredient).create({ name: 'Tomato', nameZh: '番茄', aliases: ['西红柿'], category: IngredientCategory.FRESH }));
    const recipe = await repo(Recipe).save(repo(Recipe).create({ title: 'Tomato test soup', titleZh: '番茄测试汤', descriptionZh: '一份测试汤。', tags: ['Soup'], difficulty: RecipeDifficulty.EASY, reviewStatus: RecipeReviewStatus.APPROVED, status: RecipeStatus.PUBLISHED, isPublished: true }));
    await repo(RecipeIngredient).save(repo(RecipeIngredient).create({ recipeId: recipe.id, ingredientId: tomato.id, displayName: 'Tomato', quantity: 2, unit: 'pcs' }));
    await repo(RecipeStep).save(repo(RecipeStep).create({ recipeId: recipe.id, stepNumber: 1, description: 'Wash and chop tomatoes.', descriptionZh: '洗净并切好番茄。' }));
    await repo(RecipeStep).save(repo(RecipeStep).create({ recipeId: recipe.id, stepNumber: 2, description: 'Simmer the soup.', descriptionZh: '小火煮汤。' }));
    await repo(FridgeItem).save(repo(FridgeItem).create({ userId: user.id, customName: '西红柿', quantity: 3, unit: 'pcs' }));
    const search = await service.searchRecipes({ q: '番茄', page: 1, limit: 20 });
    assert(search.items.some(r => r.id === recipe.id));
    for (const q of ['Tomatoes', '西红柿']) assert((await service.searchRecipes({ q, page: 1, limit: 20 })).items.some(r => r.id === recipe.id));
    const category = await service.searchRecipes({ q: '', category: '汤', page: 1, limit: 20 });
    assert(category.items.some(r => r.id === recipe.id));
    const detail = await service.getRecipe(recipe.id);
    assert.equal(detail.steps.length, 2);
    assert.equal(detail.steps[0].descriptionZh, '洗净并切好番茄。');
    assert.equal(detail.steps[0].description, 'Wash and chop tomatoes.');
    assert.equal(detail.descriptionZh, '一份测试汤。');
    assert.equal(detail.ingredients[0].ingredient.nameZh, '番茄');
    const cooking = await service.getRecipeForCooking(recipe.id, user.id);
    assert.equal(cooking.fridge_status[0].in_fridge, true);
    const matched = await recommendations.matchRecipesToFridge(user.id);
    assert.equal(matched.find(r => r.recipe.id === recipe.id).fridge_match_ratio, 100);
    await repo(FridgeItem).update({ userId: user.id }, { quantity: 0 });
    assert(!(await recommendations.matchRecipesToFridge(user.id)).some(r => r.recipe.id === recipe.id));
    console.log('PASS: migrations, bidirectional Chinese/English search, Chinese category filters, bilingual detail and steps, alias matching, consumed-item exclusion');
    const external = await service.searchRecipes({ q: 'Arrabiata', page: 1, limit: 20 });
    const imported = external.items.find(r => r.sourceUrl?.includes('themealdb.com'));
    assert(imported, 'Live provider did not return an imported recipe');
    const importedDetail = await service.getRecipe(imported.id);
    assert(importedDetail.ingredients.length > 0 && importedDetail.steps.length > 0);
    const before = await repo(Recipe).count();
    await service.searchRecipes({ q: 'Arrabiata', page: 1, limit: 20 });
    assert.equal(await repo(Recipe).count(), before);
    console.log('PASS: live TheMealDB search, source attribution, persisted ingredients and steps, duplicate prevention');
  } finally { await db.destroy(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
